async function listBundles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await listBundles(absolutePath))
    else if (entry.isFile() && /\.(?:js|css)$/.test(entry.name)) {
      files.push(path.relative(distDirectory, absolutePath).split(path.sep).join('/'))
    }
  }
  return files
}

async function buildServiceWorker() {
  const bundleFiles = await listBundles(path.join(distDirectory, 'assets'))
  if (!bundleFiles.some(filename => filename.endsWith('.js'))) {
    throw new Error('没有找到构建后的 JavaScript。请先运行 Vite 构建，再生成 PWA 缓存。')
  }

  const files = [...new Set([...shellFiles, ...bundleFiles, ...demoMedia])].sort()
  const checksum = createHash('sha256')
  // Changes to the worker strategy must also produce an independent cache.
  checksum.update(await readFile(fileURLToPath(import.meta.url)))
  const syncPolicy=await readFile(path.join(projectDirectory,'shared/sync-policy.mjs'),'utf8')
  checksum.update(syncPolicy)
  let totalBytes = 0
  for (const filename of files) {
    const absolutePath = path.join(distDirectory, filename)
    const fileInfo = await stat(absolutePath)
    if (!fileInfo.isFile()) throw new Error(`预缓存资源不是文件：${filename}`)
    totalBytes += fileInfo.size
    if (totalBytes > maximumPrecacheBytes) {
      throw new Error('预缓存资源超过 20 MiB 上限，请缩减媒体资源或改用按需下载。')
    }
    checksum.update(filename)
    checksum.update('\0')
    checksum.update(await readFile(absolutePath))
    checksum.update('\0')
  }

  const revision = checksum.digest('hex').slice(0, 20)
  const urls = files.map(filename => `/${filename}`)
  const worker = `/* Generated by scripts/build-pwa.mjs. Do not edit dist/sw.js. */
'use strict';

const CACHE_NAME = ${JSON.stringify(`quexin-static-${revision}`)};
const PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};
const STATIC_PATHS = new Set(PRECACHE_URLS);
const NEVER_CACHE = /(?:^|\\/)(?:api|auth|uploads?|exports?)(?:\\/|$)/i;
const SYNC_DATABASE = 'quexin-sync-state';
const SYNC_STORE = 'workspaces';

${syncPolicy.replace(/^export /gm,'')}

async function currentAccountSnapshot(userId) {
  const database=await new Promise((resolve,reject)=>{
    const request=indexedDB.open('quexin-web-account-'+userId,1);
    request.onupgradeneeded=()=>{request.transaction.abort();reject(new Error('没有此账号的资料库，暂停后台发送'));};
    request.onsuccess=()=>resolve(request.result);
    request.onerror=()=>reject(request.error||new Error('无法读取账号资料'));
  });
  try {
    const tx=database.transaction(['records','plans','journals','meta'],'readonly');
    const [records,plans,journals,settings]=await Promise.all([...['records','plans','journals'].map(name=>idbResult(tx.objectStore(name).getAll())),idbResult(tx.objectStore('meta').get('settings'))]);
    await idbDone(tx);return {records,plans,journals,boundSpaceId:settings?.value?.boundSpaceId};
  } finally {database.close();}
}

function openSyncDatabase() {
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(SYNC_DATABASE, 1);
    request.onupgradeneeded = () => {
      if (!request.result.objectStoreNames.contains(SYNC_STORE)) request.result.createObjectStore(SYNC_STORE, { keyPath: 'id' });
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error || new Error('无法打开后台同步队列'));
  });
}

function idbResult(request) {
  return new Promise((resolve, reject) => {
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error || new Error('后台同步队列读写失败'));
  });
}

function idbDone(transaction) {
  return new Promise((resolve, reject) => {
    transaction.oncomplete = () => resolve();
    transaction.onabort = () => reject(transaction.error || new Error('后台同步事务已取消'));
    transaction.onerror = () => reject(transaction.error || new Error('后台同步事务失败'));
  });
}

async function loadSyncWorkspaces() {
  const database = await openSyncDatabase();
  try {
    const transaction = database.transaction(SYNC_STORE, 'readonly');
    const rows = await idbResult(transaction.objectStore(SYNC_STORE).getAll());
    await idbDone(transaction);
    return rows;
  } finally { database.close(); }
}

async function saveSyncWorkspace(row) {
  const database = await openSyncDatabase();
  try {
    const transaction = database.transaction(SYNC_STORE, 'readwrite');
    transaction.objectStore(SYNC_STORE).put(row);
    await idbDone(transaction);
  } finally { database.close(); }
}

function retryDelay(attempts) {
  return Math.min(5 * 60 * 1000, 2000 * 2 ** Math.max(0, Math.min(8, attempts - 1)));
}

async function notifySyncClients(workspaceId) {
  const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  for (const client of windows) client.postMessage({ type: 'quexin-sync-updated', workspaceId });
}

function failedQueue(queue, message) {
  const attemptedAt = new Date().toISOString();
  return queue.map(entry => {
    const attempts = Number(entry.attempts || 0) + 1;
    return { ...entry, attempts, lastError: message, lastAttemptAt: attemptedAt, nextAttemptAt: new Date(Date.now() + retryDelay(attempts)).toISOString() };
  });
}

async function syncWorkspace(row) {
  if (!row || typeof row.id !== 'string' || !row.id.startsWith('formal:') || !Array.isArray(row.queue) || !row.queue.length) return;
  const spaceId = row.id.split(':').slice(2).join(':');
  const sessionResponse = await fetch('/formal/v1/session', {credentials:'include',cache:'no-store'});
  if(!sessionResponse.ok)return;
  const sessionEnvelope=await sessionResponse.json();
  if(!sessionEnvelope.ok||sessionEnvelope.data?.userId!==row.id.split(':')[1])return;
  const snapshot=await currentAccountSnapshot(row.id.split(':')[1]);
  if(snapshot.boundSpaceId&&snapshot.boundSpaceId!==spaceId){row.queue=[];row.conflicts=[];await saveSyncWorkspace(row);await notifySyncClients(row.id);return;}
  row.queue=pruneQueuedChanges(row.queue,snapshot);
  const privateKeys=privateEntityKeys(snapshot);
  row.conflicts=(row.conflicts||[]).filter(entry=>!privateKeys.has(entry.key));
  await saveSyncWorkspace(row);await notifySyncClients(row.id);
  if(!row.queue.length)return;
  let response;
  try {
    response = await fetch('/formal/v1/spaces/' + encodeURIComponent(spaceId) + '/sync', {
      method: 'POST', credentials: 'include', cache: 'no-store',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ commands: row.queue.map(entry => entry.command),expectedUserId:row.id.split(':')[1] })
    });
  } catch (error) {
    row.queue = failedQueue(row.queue, '后台同步暂时无法连接服务');
    await saveSyncWorkspace(row); await notifySyncClients(row.id);
    throw error;
  }
  const envelope = await response.json().catch(() => null);
  if (!response.ok || !envelope || !envelope.ok) {
    const message = envelope?.error?.message || ('后台同步失败：HTTP ' + response.status);
    row.queue = failedQueue(row.queue, message);
    await saveSyncWorkspace(row); await notifySyncClients(row.id);
    if (response.status >= 500 || response.status === 429) throw new Error(message);
    return;
  }
  const accepted = new Map(envelope.data.accepted.map(item => [item.commandId, item]));
  const conflicts = new Map(envelope.data.conflicts.map(item => [item.commandId, item]));
  const nextConflicts = Array.isArray(row.conflicts) ? [...row.conflicts] : [];
  for (const entry of row.queue) {
    const acceptedItem = accepted.get(entry.command.commandId);
    if (acceptedItem) {
      row.revisions[entry.key] = acceptedItem.revision;
      row.hashes[entry.key] = entry.hash;
    }
    const conflict = conflicts.get(entry.command.commandId);
    if (conflict) {
      const stored = { ...conflict, key: entry.key, localPayload: entry.command.payload, detectedAt: new Date().toISOString() };
      const index = nextConflicts.findIndex(item => item.key === entry.key);
      if (index >= 0) nextConflicts[index] = stored; else nextConflicts.push(stored);
    }
  }
  row.queue = row.queue.filter(entry => !accepted.has(entry.command.commandId) && !conflicts.has(entry.command.commandId));
  row.conflicts = nextConflicts;
  row.lastSyncedAt = new Date().toISOString();
  await saveSyncWorkspace(row); await notifySyncClients(row.id);
}

async function runBackgroundSync() {
  const workspaces = await loadSyncWorkspaces();
  let failure = null;
  for (const row of workspaces) {
    try {
      // Without shared Web Locks, leave retries to the page instead of racing it.
      if(!self.navigator.locks)continue;
      await self.navigator.locks.request('quexin-workspace:'+row.id,async()=>{
        const current=(await loadSyncWorkspaces()).find(item=>item.id===row.id);
        await syncWorkspace(current);
      });
    } catch (error) { failure = error; }
  }
  if (failure) throw failure;
}

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.addAll(PRECACHE_URLS)));
  // Deliberately do not skipWaiting: an update must not interrupt an open editor.
});

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(names => Promise.all(
    names.filter(name => name.startsWith('quexin-') && name !== CACHE_NAME)
      .map(name => caches.delete(name))
  )));
  // No clients.claim() or automatic reload. Normal navigation controls adoption.
});

async function navigationResponse(request) {
  try {
    const response = await fetch(request);
    if (response.ok) return response;
    // Do not disguise real 4xx responses (including authentication failures).
    if (response.status < 500) return response;
  } catch {
    // The matching build's HTML and bundles were installed together.
  }
  const cache = await caches.open(CACHE_NAME);
  const fallback = await cache.match('/index.html');
  return fallback || new Response('离线页面尚未准备好，请联网后重新打开。', {
    status: 503,
    headers: { 'Content-Type': 'text/plain; charset=utf-8' }
  });
}

async function staticResponse(request, pathname) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(pathname);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok && response.type === 'basic' && !response.redirected) {
    try { await cache.put(pathname, response.clone()); } catch {
      // A full browser cache must never break an otherwise successful response.
    }
  }
  return response;
}

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || NEVER_CACHE.test(url.pathname)) return;
  if (request.mode === 'navigate') {
    // Online HTML is intentionally not written over the precached document:
    // a newer server deployment must not mix its HTML with this worker's bundles.
    event.respondWith(navigationResponse(request));
    return;
  }
  if (STATIC_PATHS.has(url.pathname)) {
    event.respondWith(staticResponse(request, url.pathname));
  }
});

self.addEventListener('sync', event => {
  if (event.tag === 'quexin-sync') event.waitUntil(runBackgroundSync());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'quexin-sync-now') event.waitUntil(runBackgroundSync());
});
`

  await writeFile(path.join(distDirectory, 'sw.js'), worker, 'utf8')
  console.log(`PWA 缓存已生成：${files.length} 个静态资源，${(totalBytes / 1024 / 1024).toFixed(2)} MiB，版本 ${revision}`)
}

buildServiceWorker().catch(error => {
  console.error('PWA 构建失败：', error instanceof Error ? error.message : error)
  process.exitCode = 1
})
